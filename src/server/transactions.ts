// Wallets, categories and tags offered by the quick add form.
export const getFormOptions = createServerFn({ method: 'GET' })
  .middleware([authMiddleware])
  .validator(spaceInput)
  .handler(async ({ context, data }) => {
    const space = await requireMembership(context.user.id, data.spaceId)
    const [wallets, categories, tags, rules] = await Promise.all([
      db
        .select({
          id: wallet.id,
          name: wallet.name,
          currency: wallet.currency,
          icon: wallet.icon,
          color: wallet.color,
        })
        .from(wallet)
        .where(and(eq(wallet.spaceId, space.id), isNull(wallet.archivedAt)))
        .orderBy(asc(wallet.sortOrder), asc(wallet.name)),
      db
        .select({
          id: category.id,
          name: category.name,
          type: category.type,
          icon: category.icon,
          color: category.color,
          parentId: category.parentId,
        })
        .from(category)
        .where(and(eq(category.spaceId, space.id), isNull(category.archivedAt)))
        .orderBy(asc(category.name)),
      db
        .select({ id: tag.id, name: tag.name, color: tag.color })
        .from(tag)
        .where(eq(tag.spaceId, space.id))
        .orderBy(asc(tag.name)),
      db
        .select({
          type: categorizationRule.type,
          match: categorizationRule.match,
          categoryId: categorizationRule.categoryId,
        })
        .from(categorizationRule)
        .where(eq(categorizationRule.spaceId, space.id)),
    ])
    return {
      wallets,
      categories,
      tags,
      rules,
      canWrite: space.role !== 'viewer',
    }
  })

// Payee memory: the payees used most, each with the category and wallet of its latest
// transaction. With a query, matches anywhere in the name, prefix matches first.
export const suggestPayees = createServerFn({ method: 'GET' })
  .middleware([authMiddleware])
  .validator(spaceInput.extend({ query: z.string().trim().max(60) }))
  .handler(async ({ context, data }) => {
    const space = await requireMembership(context.user.id, data.spaceId)
    const pattern = data.query.replace(/[\\%_]/g, (c) => `\\${c}`)
    const byPayee = sql`lower(${transaction.payee})`
    const ranked = db
      .select({
        payee: sql<string>`${transaction.payee}`.as('payee'),
        type: transaction.type,
        categoryId: transaction.categoryId,
        walletId: transaction.walletId,
        uses: sql<number>`count(*) over (partition by ${byPayee})`.as('uses'),
        latest:
          sql<number>`row_number() over (partition by ${byPayee} order by ${transaction.date} desc, ${transaction.id} desc)`.as(
            'latest',
          ),
        prefix: sql<boolean>`${transaction.payee} ilike ${`${pattern}%`}`.as(
          'prefix',
        ),
      })
      .from(transaction)
      .where(
        and(
          eq(transaction.spaceId, space.id),
          isNotNull(transaction.payee),
          ne(transaction.type, 'transfer'),
          pattern ? ilike(transaction.payee, `%${pattern}%`) : undefined,
        ),
      )
      .as('ranked')
    return db
      .select({
        payee: ranked.payee,
        type: ranked.type,
        categoryId: ranked.categoryId,
        walletId: ranked.walletId,
      })
      .from(ranked)
      .where(eq(ranked.latest, 1))
      .orderBy(desc(ranked.prefix), desc(ranked.uses), asc(ranked.payee))
      .limit(6)
  })

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .nullable()
    .transform((value) => value || null)

const transactionInput = spaceInput.extend({
  // Generated by the client (UUIDv7), so optimistic rows keep their id.
  id: z.uuid(),
  type: z.enum(['income', 'expense', 'transfer']),
  date: z.iso.date(),
  walletId: z.uuid(),
  amount: z.int().positive().max(Number.MAX_SAFE_INTEGER),
  categoryId: z.uuid().nullable(),
  toWalletId: z.uuid().nullable(),
  toAmount: z.int().positive().max(Number.MAX_SAFE_INTEGER).nullable(),
  payee: optionalText(120),
  note: optionalText(2000),
  tagIds: z.array(z.uuid()).max(20),
  // Parts of a split receipt (M-14): none, or at least two that add up to the amount.
  splits: z
    .array(
      z.object({
        categoryId: z.uuid(),
        amount: z.int().positive().max(Number.MAX_SAFE_INTEGER),
        note: optionalText(200),
      }),
    )
    .max(20)
    .default([]),
})
export type TransactionInput = z.input<typeof transactionInput>
type ValidInput = z.output<typeof transactionInput>

// Checks the role and the tags; checkMovement covers wallets, category and currencies.
// Returns the row to store.
async function prepare(userId: string, input: ValidInput) {
  const space = await requireMembership(userId, input.spaceId)
  if (space.role === 'viewer')
    throw new Error('Viewers cannot change this space.')

  const split = input.splits.length > 0
  if (split) {
    if (input.splits.length < 2)
      throw new Error('A split needs at least two parts.')
    const total = input.splits.reduce((sum, p) => sum + p.amount, 0)
    if (total !== input.amount)
      throw new Error('The parts must add up to the amount.')
  }
  const splitCategoryIds = [...new Set(input.splits.map((p) => p.categoryId))]
  const [movement, tags, splitCategories] = await Promise.all([
    checkMovement(space.id, input, { split }),
    input.tagIds.length
      ? db
          .select({ id: tag.id })
          .from(tag)
          .where(and(eq(tag.spaceId, space.id), inArray(tag.id, input.tagIds)))
      : Promise.resolve([]),
    split
      ? db
          .select({ id: category.id, type: category.type })
          .from(category)
          .where(
            and(
              eq(category.spaceId, space.id),
              inArray(category.id, splitCategoryIds),
            ),
          )
      : Promise.resolve([]),
  ])
  if (tags.length !== new Set(input.tagIds).size)
    throw new Error('Unknown tag.')
  if (
    splitCategories.length !== splitCategoryIds.length ||
    splitCategories.some((c) => c.type !== input.type)
  )
    throw new Error(`Choose ${input.type} categories for the parts.`)

  return {
    space,
    row: {
      id: input.id,
      spaceId: space.id,
      type: input.type,
      date: input.date,
      walletId: input.walletId,
      amount: input.amount,
      ...movement,
      payee: input.payee,
      note: input.note,
    },
    tagIds: [...new Set(input.tagIds)],
    splits: input.splits.map((p) => ({
      ...p,
      spaceId: space.id,
      transactionId: input.id,
    })),
  }
}

export const createTransaction = createServerFn({ method: 'POST' })
  .middleware([authMiddleware])
  .validator(transactionInput)
  .handler(async ({ context, data }) => {
    const { row, tagIds, splits } = await prepare(context.user.id, data)
    await db.transaction(async (tx) => {
      // A retried request with the same id is a no-op.
      const inserted = await tx
        .insert(transaction)
        .values({ ...row, createdBy: context.user.id })
        .onConflictDoNothing({ target: transaction.id })
        .returning({ id: transaction.id })
      if (inserted.length)
        await logActivity(tx, context.user.id, 'created', row)
      if (inserted.length && splits.length)
        await tx.insert(transactionSplit).values(splits)
      if (inserted.length && tagIds.length) {
        await tx.insert(transactionTag).values(
          tagIds.map((tagId) => ({
            spaceId: row.spaceId,
            transactionId: row.id,
            tagId,
          })),
        )
      }
    })
    return { id: row.id }
  })

export const updateTransaction = createServerFn({ method: 'POST' })
  .middleware([authMiddleware])
  .validator(transactionInput)
  .handler(async ({ context, data }) => {
    const { row, tagIds, splits } = await prepare(context.user.id, data)
    const { id, spaceId, ...changes } = row
    await db.transaction(async (tx) => {
      const [before] = await tx
        .select({
          payee: transaction.payee,
          amount: transaction.amount,
          date: transaction.date,
        })
        .from(transaction)
        .where(and(eq(transaction.id, id), eq(transaction.spaceId, spaceId)))
        .for('update')
      if (!before) throw new Error('Transaction not found.')
      await tx.update(transaction).set(changes).where(eq(transaction.id, id))
      await logActivity(tx, context.user.id, 'updated', row, before)
      await tx
        .delete(transactionSplit)
        .where(eq(transactionSplit.transactionId, id))
      if (splits.length) await tx.insert(transactionSplit).values(splits)
      await tx
        .delete(transactionTag)
        .where(eq(transactionTag.transactionId, id))
      if (tagIds.length) {
        await tx
          .insert(transactionTag)
          .values(
            tagIds.map((tagId) => ({ spaceId, transactionId: id, tagId })),
          )
      }
    })
    return { id }
  })

export const deleteTransaction = createServerFn({ method: 'POST' })
  .middleware([authMiddleware])
  .validator(spaceInput.extend({ id: z.uuid() }))
  .handler(async ({ context, data }) => {
    const space = await requireMembership(context.user.id, data.spaceId)
    if (space.role === 'viewer')
      throw new Error('Viewers cannot change this space.')
    await db.transaction(async (tx) => {
      // Tags and splits go with the row (cascade), so the log keeps them for a restore.
      const [tags, splits] = await Promise.all([
        tx
          .select({ tagId: transactionTag.tagId })
          .from(transactionTag)
          .where(eq(transactionTag.transactionId, data.id)),
        tx
          .select({
            categoryId: transactionSplit.categoryId,
            amount: transactionSplit.amount,
            note: transactionSplit.note,
          })
          .from(transactionSplit)
          .where(eq(transactionSplit.transactionId, data.id)),
      ])
      const [deleted] = await tx
        .delete(transaction)
        .where(
          and(eq(transaction.id, data.id), eq(transaction.spaceId, space.id)),
        )
        .returning()
      if (deleted)
        await logActivity(tx, context.user.id, 'deleted', deleted, undefined, {
          categoryId: deleted.categoryId,
          toWalletId: deleted.toWalletId,
          toAmount: deleted.toAmount,
          note: deleted.note,
          createdBy: deleted.createdBy,
          recurringRuleId: deleted.recurringRuleId,
          importId: deleted.importId,
          tagIds: tags.map((t) => t.tagId),
          splits,
        })
    })
    return { id: data.id }
  })

// Puts a deleted transaction back from its snapshot in the activity log (I-13), with its
// tags and splits. Links to a recurring rule, an import or tags that are gone since are
// dropped; a missing wallet or category stops the restore.
export const restoreTransaction = createServerFn({ method: 'POST' })
  .middleware([authMiddleware])
  .validator(spaceInput.extend({ eventId: z.uuid() }))
  .handler(async ({ context, data }) => {
    const space = await requireMembership(context.user.id, data.spaceId)
    if (space.role === 'viewer')
      throw new Error('Viewers cannot change this space.')
    const [event] = await db
      .select()
      .from(activityEvent)
      .where(
        and(
          eq(activityEvent.id, data.eventId),
          eq(activityEvent.spaceId, space.id),
          eq(activityEvent.action, 'deleted'),
          gte(
            activityEvent.createdAt,
            new Date(Date.now() - RESTORE_DAYS * 86_400_000),
          ),
        ),
      )
    const snapshot = event?.details.snapshot
    if (!event || !snapshot) throw new Error('This deletion cannot be undone.')
    const { details } = event

    const walletIds = [details.walletId, snapshot.toWalletId].filter(
      (id): id is string => id !== null,
    )
    const categoryIds = [
      snapshot.categoryId,
      ...snapshot.splits.map((p) => p.categoryId),
    ].filter((id): id is string => id !== null)
    const [wallets, categories, rules, imports, tags] = await Promise.all([
      db
        .select({ id: wallet.id })
        .from(wallet)
        .where(
          and(eq(wallet.spaceId, space.id), inArray(wallet.id, walletIds)),
        ),
      categoryIds.length
        ? db
            .select({ id: category.id })
            .from(category)
            .where(
              and(
                eq(category.spaceId, space.id),
                inArray(category.id, categoryIds),
              ),
            )
        : Promise.resolve([]),
      snapshot.recurringRuleId
        ? db
            .select({ id: recurringRule.id })
            .from(recurringRule)
            .where(eq(recurringRule.id, snapshot.recurringRuleId))
        : Promise.resolve([]),
      snapshot.importId
        ? db
            .select({ id: importBatch.id })
            .from(importBatch)
            .where(eq(importBatch.id, snapshot.importId))
        : Promise.resolve([]),
      snapshot.tagIds.length
        ? db
            .select({ id: tag.id })
            .from(tag)
            .where(
              and(eq(tag.spaceId, space.id), inArray(tag.id, snapshot.tagIds)),
            )
        : Promise.resolve([]),
    ])
    if (
      wallets.length !== new Set(walletIds).size ||
      categories.length !== new Set(categoryIds).size
    )
      throw new Error('Its wallet or category no longer exists.')

    const row = {
      id: event.transactionId,
      spaceId: space.id,
      type: details.type,
      date: details.date,
      walletId: details.walletId,
      amount: details.amount,
      categoryId: snapshot.categoryId,
      toWalletId: snapshot.toWalletId,
      toAmount: snapshot.toAmount,
      payee: details.payee,
      note: snapshot.note,
      createdBy: snapshot.createdBy,
      recurringRuleId: rules[0]?.id ?? null,
      importId: imports[0]?.id ?? null,
    }
    await db.transaction(async (tx) => {
      const inserted = await tx
        .insert(transaction)
        .values(row)
        .onConflictDoNothing({ target: transaction.id })
        .returning({ id: transaction.id })
      if (!inserted.length) throw new Error('It has been restored already.')
      if (snapshot.splits.length)
        await tx.insert(transactionSplit).values(
          snapshot.splits.map((p) => ({
            ...p,
            spaceId: space.id,
            transactionId: row.id,
          })),
        )
      if (tags.length)
        await tx.insert(transactionTag).values(
          tags.map((t) => ({
            spaceId: space.id,
            transactionId: row.id,
            tagId: t.id,
          })),
        )
      await logActivity(tx, context.user.id, 'created', row)
    })
    return { id: row.id }
  })
